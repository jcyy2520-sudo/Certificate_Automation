import { test, expect } from '@playwright/test';

test('Certificate Setup previews draft copy, saves it, and confirms a sample-only test delivery', async ({ page, context }) => {
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto('/admin/login');
    await page.getByLabel('Email', { exact: true }).fill('workflow@example.test');
    await page.getByLabel('Password', { exact: true }).fill('Workflow-fixture-2026!');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.goto('/admin/webinars/1/certification');
    await expect(page.getByRole('heading', { name: 'Certificate Setup', exact: true })).toBeVisible();
    await expect(page.getByLabel('Template name', { exact: true })).toHaveCount(0);
    await expect(page.locator('input[name^="rules["]')).toHaveCount(0);
    await expect(page.locator('[data-template-designer]')).toBeVisible();
    await page.getByLabel('Email Subject', { exact: true }).fill('For {{participant_name}} — {{webinar_title}}');
    await page.getByLabel('Email Message', { exact: true }).fill('Dear {{participant_name}},\n\nYour {{certificate_type}} for {{webinar_title}} is attached.\n\nWebinar Organizing Team');
    const previewPromise = context.waitForEvent('page');
    await page.getByRole('button', { name: 'Preview Email', exact: true }).click();
    const preview = await previewPromise;
    await expect(preview.getByText('Email preview — no email sent', { exact: true })).toBeVisible();
    await expect(preview.locator('body')).toContainText('For Sample Participant — Workflow browser fixture');
    await expect(preview.locator('body')).toContainText('Your Certificate of Participation for Workflow browser fixture is attached.');
    await expect(preview.locator('body')).toContainText('certificate.pdf');
    await preview.close();
    await page.getByRole('button', { name: 'Save email configuration', exact: true }).click();
    await expect(page.getByText('Email configuration saved. No certificates or emails were sent.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Send Test Email', exact: true }).click();
    await expect(page.locator('[data-confirm-modal]')).toBeVisible();
    await page.locator('[data-confirm-cancel]').click();
    await page.getByRole('button', { name: 'Send Test Email', exact: true }).click();
    await page.locator('[data-confirm-accept]').click();
    await expect(page.getByText('One sample email was queued', { exact: false })).toBeVisible();
    await page.getByRole('link', { name: 'View pending, sent and failed deliveries', exact: true }).click();
    await expect(page.locator('tbody')).toContainText('Certificate test (administrator only)');
    await expect(page.locator('tbody')).toContainText('Pending');
    await page.goto('/admin/webinars/1/certification');
    await page.evaluate(() => localStorage.setItem('theme', 'light'));
    await page.reload();
    await page.screenshot({ path: 'storage/framework/testing/certificate-setup-desktop-light.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Toggle theme' }).filter({ visible: true }).click();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await expect(page.getByLabel('Email Message', { exact: true })).toHaveValue(/Dear \{\{participant_name\}\}/);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: 'storage/framework/testing/certificate-setup-mobile-dark.png', fullPage: true });
    await page.getByLabel('Email Message', { exact: true }).fill('Dear {{unknown_placeholder}}');
    await page.getByRole('button', { name: 'Save email configuration', exact: true }).click();
    await expect(page.getByText('Use only {{participant_name}}, {{webinar_title}} or {{certificate_type}}.', { exact: true }).first()).toBeVisible();
    expect(errors).toEqual([]);
});
