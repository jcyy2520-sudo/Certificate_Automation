import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { workflowEnvironment } from '../../playwright.workflow.config.js';

test('admin invitation, individual activation, assigned access and audit filters work through HTTP', async ({ page, browser }) => {
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const fixture = (...args) => execFileSync('php', ['tests/workflow/invitation-fixture.php', ...args], { env: workflowEnvironment, encoding: 'utf8' }).trim();
    await page.goto('/admin/login');
    await page.getByLabel('Email', { exact: true }).fill('inviter@example.test');
    await page.getByLabel('Password', { exact: true }).fill('Inviter-fixture-2026!');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.getByLabel('Authentication code', { exact: true }).fill(fixture('otp', '0'));
    await page.getByRole('button', { name: 'Verify and sign in', exact: true }).click();
    await page.goto('/admin/users');
    await page.getByRole('button', { name: 'Create Account', exact: true }).click();
    let dialog = page.getByRole('dialog', { name: 'Create Account', exact: true });
    await expect(dialog).toBeVisible();
    await dialog.getByLabel('Full Name', { exact: true }).fill('Invited Browser Manager');
    await dialog.getByLabel('Email Address', { exact: true }).fill('invited.browser@example.test');
    await dialog.getByLabel('Workflow browser fixture', { exact: true }).check();
    await dialog.getByLabel('Manage participants, responses, forms and documents', { exact: true }).check();
    await expect(dialog.getByLabel('Your current password', { exact: true })).toHaveCount(0);
    await dialog.getByLabel('Authenticator code', { exact: true }).fill('invalid');
    await dialog.getByRole('button', { name: 'Create and invite', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'Create Account', exact: true });
    await expect(dialog).toBeVisible();
    await expect(dialog.getByRole('alert')).toContainText('code');
    await expect(dialog.getByLabel('Full Name', { exact: true })).toHaveValue('Invited Browser Manager');
    await expect(dialog.getByLabel('Your current password', { exact: true })).toHaveCount(0);
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.screenshot({ path: 'storage/framework/testing/invitation-desktop-light.png', fullPage: true });
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Toggle theme', exact: true }).filter({ visible: true }).click();
    await page.setViewportSize({ width: 375, height: 812 });
    await page.getByRole('button', { name: 'Create Account', exact: true }).click();
    await page.screenshot({ path: 'storage/framework/testing/invitation-mobile-dark.png', fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await expect(dialog.getByLabel('Your current password', { exact: true })).toHaveCount(0);
    await dialog.getByLabel('Authenticator code', { exact: true }).fill(fixture('otp', '1'));
    await dialog.getByRole('button', { name: 'Create and invite', exact: true }).click();
    await expect(page.getByText('Account created. Activation email queued;', { exact: false })).toBeVisible();
    const row = page.locator('tbody tr').filter({ hasText: 'invited.browser@example.test' });
    await expect(row).toContainText('Pending activation');
    await expect(row).toContainText('Webinar Manager');
    await expect(row).toContainText('Workflow browser fixture');
    await page.setViewportSize({ width: 768, height: 1024 });
    await page.screenshot({ path: 'storage/framework/testing/invitations-tablet-dark.png', fullPage: true });

    const context = await browser.newContext();
    const member = await context.newPage();
    member.on('pageerror', e => errors.push(e.message));
    const link = fixture('invitation');
    await member.goto(link);
    await member.getByLabel('New password', { exact: true }).fill('Invited browser personal passphrase!');
    await member.getByLabel('Confirm password', { exact: true }).fill('Invited browser personal passphrase!');
    await member.getByRole('button', { name: 'Save password', exact: true }).click();
    await member.getByLabel('Email', { exact: true }).fill('invited.browser@example.test');
    await member.getByLabel('Password', { exact: true }).fill('Invited browser personal passphrase!');
    await member.getByRole('button', { name: 'Sign in', exact: true }).click();
    await member.goto('/admin/webinars/1');
    await expect(member.getByRole('heading', { name: 'Workflow browser fixture', exact: true })).toBeVisible();
    await expect(member.getByRole('link', { name: 'User Management', exact: true })).toHaveCount(0);
    await expect(member.getByRole('link', { name: 'Certificate Studio', exact: true })).toHaveCount(0);
    await member.goto('/admin/users');
    await expect(member.getByText('403', { exact: true })).toBeVisible();
    await member.goto('/admin/audit-trail');
    await expect(member.getByText('403', { exact: true })).toBeVisible();
    await page.goto('/admin/audit-trail?action=account.invited');
    await expect(page.getByText('account.invited', { exact: false }).first()).toBeVisible();
    await expect(page.locator('article').filter({ hasText: 'account.invited' }).first()).toContainText('Invitation Reviewer');
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.screenshot({ path: 'storage/framework/testing/audit-desktop-dark.png', fullPage: true });
    expect(errors).toEqual([]);
    await context.close();
});
