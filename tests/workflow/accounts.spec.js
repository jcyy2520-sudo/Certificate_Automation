import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { workflowEnvironment } from '../../playwright.workflow.config.js';

test('account approval, setup, ownership, optional locks and suspension work through real HTTP', async ({ page, browser }) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const mail = type => execFileSync('php', ['tests/workflow/account-mail.php', type], { env: workflowEnvironment, encoding: 'utf8' }).trim();
    await page.goto('/admin/login');
    await page.getByRole('link', { name: 'Request an account', exact: true }).click();
    await page.getByRole('button', { name: 'Request account', exact: true }).click();
    await expect(page.locator('#name-error')).toHaveText('The name field is required.');
    await page.getByLabel('Full name', { exact: true }).fill('Browser Account Owner');
    await page.getByLabel('Email address', { exact: true }).fill('browser.account@example.test');
    await page.getByRole('button', { name: 'Request account', exact: true }).click();
    await expect(page.getByText('Your request has been received for administrator review.', { exact: false })).toBeVisible();
    await page.goto('/admin/login');
    await page.getByLabel('Email', { exact: true }).fill('workflow@example.test');
    await page.getByLabel('Password', { exact: true }).fill('Workflow-fixture-2026!');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.goto('/admin/users');
    await expect(page.locator('tbody')).toContainText('Browser Account Owner');
    await page.getByRole('button', { name: 'Approve', exact: true }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await page.getByRole('button', { name: 'Approve', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Approve', exact: true }).click();
    await expect(page.getByText('Account updated.', { exact: false })).toBeVisible();
    await page.goto('/admin/users?status=approved');
    await page.setViewportSize({ width: 1280, height: 850 });
    await page.screenshot({ path: 'storage/framework/testing/accounts-desktop-light.png', fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 375, height: 812 });
    await page.getByRole('button', { name: 'Toggle theme', exact: true }).filter({ visible: true }).click();
    await page.screenshot({ path: 'storage/framework/testing/accounts-mobile-dark.png', fullPage: true, animations: 'disabled' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);

    const ownerContext = await browser.newContext();
    const owner = await ownerContext.newPage();
    owner.on('pageerror', error => errors.push(error.message));
    await owner.goto(mail('account_setup'));
    await owner.getByLabel('New password', { exact: true }).fill('Browser member long passphrase!');
    await owner.getByRole('button', { name: 'Show new password', exact: true }).click();
    await expect(owner.getByLabel('New password', { exact: true })).toHaveAttribute('type', 'text');
    await owner.getByLabel('Confirm password', { exact: true }).fill('Browser member long passphrase!');
    await owner.getByRole('button', { name: 'Save password', exact: true }).click();
    await owner.getByLabel('Email', { exact: true }).fill('browser.account@example.test');
    await owner.getByLabel('Password', { exact: true }).fill('Browser member long passphrase!');
    await owner.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(owner.getByRole('link', { name: 'User Management', exact: true })).toHaveCount(0);
    await owner.goto('/admin/webinars/1');
    await expect(owner.getByText('404', { exact: true })).toBeVisible();
    await owner.goto('/admin/webinars/create');
    await owner.locator('input[name=title]').fill('Owned browser webinar');
    await owner.getByLabel('Password-protect this webinar', { exact: true }).check();
    await owner.getByLabel('Webinar password', { exact: true }).fill('Secondary webinar passphrase!');
    await owner.getByLabel('Confirm webinar password', { exact: true }).fill('Secondary webinar passphrase!');
    await owner.getByRole('button', { name: 'Create webinar', exact: true }).click();
    await expect(owner.getByRole('heading', { name: 'Unlock webinar', exact: true })).toBeVisible();
    await owner.getByLabel('Webinar password', { exact: true }).fill('incorrect');
    await owner.getByRole('button', { name: 'Unlock webinar', exact: true }).click();
    await expect(owner.getByText('The webinar password is incorrect.', { exact: true }).first()).toBeVisible();
    await owner.getByLabel('Webinar password', { exact: true }).fill('Secondary webinar passphrase!');
    await owner.getByRole('button', { name: 'Unlock webinar', exact: true }).click();
    await expect(owner.getByRole('heading', { name: 'Overview', exact: true })).toBeVisible();
    const ownedUrl = owner.url();
    await owner.goto(ownedUrl + '/responses');
    await expect(owner.getByRole('heading', { name: 'Unlock webinar', exact: true })).toHaveCount(0);

    await page.reload();
    const row = page.locator('tbody tr').filter({ hasText: 'browser.account@example.test' });
    await row.getByRole('button', { name: 'Disable Account', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Disable Account', exact: true }).click();
    await expect(page.getByText('Account updated.', { exact: false })).toBeVisible();
    await owner.goto(ownedUrl);
    await expect(owner.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible();
    expect(errors).toEqual([]);
    await ownerContext.close();
});
