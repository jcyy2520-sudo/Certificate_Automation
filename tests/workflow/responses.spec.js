import { test, expect } from '@playwright/test';

test('native collection, reviewed imports, eligibility and automatic Studio recipients work in a browser', async ({ page, context }) => {
    // Four complete form/import reviews plus PDF and responsive Studio checks.
    test.setTimeout(180000);
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto('/admin/login');
    await page.getByLabel('Email', { exact: true }).fill('workflow@example.test');
    await page.getByLabel('Password', { exact: true }).fill('Workflow-fixture-2026!');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.goto('/admin/webinars/1/forms/1/edit');
    await expect(page.getByRole('navigation', { name: 'Forms', exact: true })).toBeVisible();
    await expect(page.getByRole('link', { name: 'CSV imports', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Toggle theme' }).filter({ visible: true }).click();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.reload();
    await expect(page.locator('html')).toHaveClass(/dark/);
    const participantPage = await context.newPage();
    for (const [index, type] of ['registration', 'pretest', 'posttest', 'evaluation'].entries()) {
        await page.goto(`/admin/webinars/1/forms/${index + 1}/edit`);
        const shareUrl = await page.locator('input[readonly]').first().inputValue();
        await participantPage.goto(shareUrl);
        await participantPage.getByLabel(/Full name/).fill('Native Browser Participant');
        await participantPage.getByLabel('Email address', { exact: false }).fill('browser.native@example.test');
        await participantPage.getByRole('radio', { name: 'Very useful', exact: true }).check();
        await participantPage.locator('input[name="privacy_acknowledged"]').check();
        await participantPage.getByRole('button', { name: 'Submit', exact: true }).click();
        await expect(participantPage.getByText('Your response has been recorded', { exact: false })).toBeVisible();
        await page.goto(`/admin/webinars/1/responses?type=${type}`);
        await expect(page.locator('tbody')).toContainText('browser.native@example.test');
        await page.getByRole('link', { name: 'Import Responses', exact: true }).click();
        await expect(page.locator('select[name="form_id"]')).toHaveValue(String(index + 1));
        await page.locator('input[type="file"]').setInputFiles({ name: `${type}.csv`, mimeType: 'text/csv', buffer: Buffer.from('Email,Full Name,Session feedback\nbrowser.imported@example.test,Imported Browser Participant, Useful \n') });
        await page.getByRole('button', { name: 'Continue to column mapping' }).click();
        await page.locator(`select[name="answer_map[field_${index + 1}]"]`).selectOption('2');
        if (type !== 'registration') await page.locator('input[name="required_columns[]"][value="2"]').check();
        await page.locator('input[name="allow_import_time"]').check();
        await page.locator('input[name="source_description"]').fill(`Browser ${type} form export v1`);
        await page.locator('input[name="source_confirmed"]').check();
        await page.getByRole('button', { name: 'Run dry check' }).click();
        await expect(page.getByText('Dry run complete', { exact: false })).toBeVisible();
        await page.locator('input[name="review_confirmed"]').check();
        await page.getByRole('button', { name: 'Import reviewed responses' }).click();
        await page.goto(`/admin/webinars/1/responses?type=${type}`);
        await expect(page.locator('tbody')).toContainText('browser.imported@example.test');
        await expect(page.locator('tbody')).toContainText('Useful');
        await page.getByRole('link', { name: 'Summary', exact: true }).click();
        await expect(page.locator('.summary-bar').filter({ has: page.getByText('Useful', { exact: true }) })).toContainText('1 (50%)');
        await expect(page.getByText('unrecognized choice value(s)', { exact: false })).toHaveCount(0);
    }
    await participantPage.close();
    await page.goto('/admin/webinars/1/responses?view=settings');
    for (const type of ['registration', 'pretest', 'posttest']) await page.locator(`input[name="rules[${type}][enabled]"]`).check();
    await page.locator('input[name="rules[evaluation][enabled]"]').uncheck();
    await page.getByRole('button', { name: 'Save eligibility settings' }).click();
    await page.getByRole('link', { name: 'Eligibility review', exact: true }).click();
    await expect(page.locator('tbody')).toContainText('Eligible');
    await expect(page.locator('tbody')).toContainText('Available automatically');
    await expect(page.getByRole('button', { name: 'Approve for Certificates', exact: true })).toHaveCount(0);
    await page.screenshot({ path: 'storage/app/private/workflow-desktop-dark.png', fullPage: true });
    await page.getByRole('link', { name: 'Open Certificate Studio', exact: true }).click();
    await expect(page.locator('[data-queue-check]')).toHaveCount(2);
    await page.screenshot({ path: 'storage/framework/testing/frontend-studio-desktop-dark.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Open editor', exact: true }).click();
    await page.getByRole('textbox', { name: 'Hex colour' }).fill('#112233');
    await page.getByRole('textbox', { name: 'Hex colour' }).blur();
    await expect(page.getByRole('link', { name: 'Preview PDF', exact: true }).filter({ visible: true })).toBeVisible();
    const pdfPreviewUrl = new URL(await page.getByRole('link', { name: 'Preview PDF', exact: true }).filter({ visible: true }).getAttribute('href'), page.url());
    expect(pdfPreviewUrl.searchParams.has('name')).toBe(false);
    expect(pdfPreviewUrl.searchParams.get('participant')).toBeTruthy();
    const pdfPreview = await page.request.get(pdfPreviewUrl.href);
    expect(pdfPreview.status()).toBe(200);
    expect(pdfPreview.headers()['content-type']).toContain('application/pdf');
    const typedPreview = await page.request.post(pdfPreviewUrl.pathname, { form: {
        _token: await page.locator('meta[name="csrf-token"]').getAttribute('content'),
        name: 'Synthetic Preview Name',
    } });
    expect(typedPreview.status()).toBe(200);
    expect(typedPreview.headers()['content-type']).toContain('application/pdf');
    await expect(page.getByRole('link', { name: 'Export ZIP', exact: true }).filter({ visible: true })).toBeVisible();
    await page.getByRole('spinbutton', { name: 'Vertical position' }).fill('0');
    await page.getByRole('spinbutton', { name: 'Vertical position' }).blur();
    await expect(page.locator('[data-design-top]')).toHaveValue('0.00');
    await page.getByRole('spinbutton', { name: 'Vertical position' }).fill('55');
    await page.getByRole('spinbutton', { name: 'Vertical position' }).blur();
    await page.screenshot({ path: 'storage/framework/testing/frontend-studio-phone-dark.png', fullPage: true });
    await page.getByRole('button', { name: 'Close editor', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Open editor', exact: true })).toBeFocused();
    await page.getByRole('button', { name: 'Open recipients', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Close recipients', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Close recipients', exact: true }).click();
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.locator('[data-reset-design]').click();

    await page.getByRole('button', { name: 'Toggle theme' }).click();
    await expect(page.locator('html')).not.toHaveClass(/dark/);
    await page.screenshot({ path: 'storage/framework/testing/frontend-studio-desktop-light.png', fullPage: true });
    await page.setViewportSize({ width: 768, height: 1024 });
    await page.goto('/admin/webinars/1/forms/2/edit');
    await expect(page.getByRole('link', { name: 'Preview form', exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: 'storage/app/private/workflow-tablet-forms-light.png', fullPage: true });
    await page.goto('/admin/webinars/1/responses');
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByRole('button', { name: 'Open webinar navigation' })).toBeVisible();
    await page.getByRole('button', { name: 'Open webinar navigation' }).click();
    await expect(page.getByRole('link', { name: 'Form Responses', exact: true }).filter({ visible: true })).toBeVisible();
    await page.keyboard.press('Escape');
    await page.screenshot({ path: 'storage/app/private/workflow-mobile-light.png', fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.getByRole('button', { name: 'Toggle theme' }).filter({ visible: true }).click();
    await page.getByRole('link', { name: 'Summary', exact: true }).click();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.screenshot({ path: 'storage/app/private/workflow-mobile-dark-summary.png', fullPage: true });
    expect(errors).toEqual([]);
});
