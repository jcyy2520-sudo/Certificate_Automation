import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { workflowEnvironment } from '../../playwright.workflow.config.js';

test('eligibility roster, private review, verified correction and notifications work through real HTTP', async ({ page, browser }) => {
    test.setTimeout(120000);
    const fixture = (...args) => execFileSync('php', ['tests/workflow/eligibility-fixture.php', ...args], { env: workflowEnvironment, encoding: 'utf8' }).trim();
    const data = JSON.parse(fixture());
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/admin/login');
    await page.getByLabel('Email', { exact: true }).fill('workflow@example.test');
    await page.getByLabel('Password', { exact: true }).fill('Workflow-fixture-2026!');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.goto(`/admin/webinars/${data.webinar}/certificates/studio`);
    await page.getByRole('tab', { name: 'Not eligible', exact: false }).click();
    await expect(page.locator('[data-tab-panel="incomplete"]')).toBeVisible();
    await expect(page.locator('[data-tab-panel="incomplete"]')).toContainText('Pending Eligibility Person');
    await expect(page.locator('[data-tab-panel="incomplete"] [data-queue-check]')).toHaveCount(0);
    await page.screenshot({ path: 'storage/framework/testing/eligibility-studio-desktop.png' });
    await page.goto(`/admin/webinars/${data.webinar}/eligibility`);
    await expect(page.getByRole('heading', { name: 'Participant Eligibility', exact: true })).toBeVisible();
    await page.getByLabel('Select Pending Eligibility Person', { exact: true }).check();
    await expect(page.locator('[data-message-count]')).toHaveText('1');
    await page.locator('[data-message-submit]').click();
    await expect(page.locator('[data-confirm-message]')).toContainText('1 selected recipients');
    await page.locator('[data-confirm-accept]').click();
    await expect(page.getByText('1 eligibility notification(s) queued.', { exact: false })).toBeVisible();
    const personalContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const participant = await personalContext.newPage();
    participant.on('pageerror', error => errors.push(error.message));
    await participant.goto(data.personalUrl);
    await participant.getByRole('button', { name: 'Continue to participant status', exact: true }).click();
    await expect(participant.getByRole('heading', { name: 'Incomplete / Under Review', exact: true })).toBeVisible();
    await expect(participant.getByText('Under Review', { exact: true })).toBeVisible();
    await expect(participant.getByText('Not required for eligibility', { exact: true })).toBeVisible();
    await participant.getByText('Request Record Review', { exact: true }).click();
    await participant.getByLabel('What should the organizer check?', { exact: true }).fill('Please verify my post assessment against the original source export.');
    await participant.getByLabel('Supporting evidence (optional)', { exact: true }).setInputFiles({ name: 'evidence.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nSynthetic review evidence') });
    await participant.getByRole('button', { name: 'Submit review request', exact: true }).click();
    await expect(participant.getByText('Your review request is pending.', { exact: false })).toBeVisible();
    await participant.evaluate(() => { localStorage.setItem('theme', 'dark'); document.documentElement.classList.add('dark'); });
    expect(await participant.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await participant.screenshot({ path: 'storage/framework/testing/eligibility-participant-mobile-dark.png', fullPage: true });
    await page.goto(`/admin/webinars/${data.webinar}/eligibility/${data.pending}`);
    await page.locator('[data-noneligible-message-preview] summary').click();
    await expect(page.locator('[data-noneligible-message-preview]')).toContainText('Post-Test');
    await expect(page.locator('[data-noneligible-message-preview] a')).toHaveCount(0);
    await page.getByLabel('Decision', { exact: true }).selectOption('approved');
    await page.getByLabel('For approval: verified correction', { exact: true }).selectOption('existing_import');
    await page.getByLabel('Held import issue number (when applying an import)', { exact: true }).fill(String(data.issue));
    await page.getByLabel('Reason visible to participant', { exact: true }).fill('Verified the original export and matched this post assessment by email.');
    await page.getByRole('button', { name: 'Save decision', exact: true }).click();
    await page.locator('[data-confirm-accept]').click();
    await expect(page.getByRole('heading', { name: 'Eligible', exact: true })).toBeVisible();
    await participant.reload();
    await expect(participant.getByRole('heading', { name: 'Eligible', exact: true })).toBeVisible();
    await expect(participant.getByText('Organizer’s decision:', { exact: false })).toContainText('Verified the original export');
    await expect(participant.getByText('No valid certificate is available yet.', { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 820, height: 1180 });
    await page.evaluate(() => { localStorage.setItem('theme', 'dark'); document.documentElement.classList.add('dark'); });
    await page.goto(`/admin/webinars/${data.webinar}/eligibility`);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: 'storage/framework/testing/eligibility-admin-tablet-dark.png', fullPage: true });
    await personalContext.close();
    expect(errors).toEqual([]);
});
